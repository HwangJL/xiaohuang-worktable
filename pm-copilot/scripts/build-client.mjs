/**
 * Build the Client artifact: concatenate `src-client/*.js` in filename order
 * into the single `client.js` that DSH serves to the page.
 *
 * The parts are plain JavaScript fragments of one lazy factory; there is no
 * bundler, no TypeScript step and no third-party dependency. Run:
 *
 *   node scripts/build-client.mjs
 *
 * The artifact is committed, so installing the package never requires a build.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const sourceDir = join(root, 'src-client')
const target = join(root, 'client.js')

const files = readdirSync(sourceDir).filter((name) => name.endsWith('.js')).sort()
if (files.length === 0) throw new Error('src-client has no .js parts')

const banner = [
  '/**',
  ' * PM Copilot — Client artifact. GENERATED by scripts/build-client.mjs:',
  ' * edit src-client/*.js and rebuild; never edit this file by hand.',
  ' */',
].join('\n')

const body = files.map((name) => '/* ---- ' + name + ' ---- */\n' + readFileSync(join(sourceDir, name), 'utf8')).join('\n')
writeFileSync(target, banner + '\n' + body + '\n', 'utf8')

const bytes = readFileSync(target).length
process.stdout.write('wrote client.js from ' + files.length + ' part(s), ' + bytes + ' bytes\n')
